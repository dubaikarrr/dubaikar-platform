import { NextResponse, type NextRequest } from "next/server";
import { createClient } from "@/lib/supabase/server";
import { launchBrowser } from "@/lib/resume/browser";
import {
  calculateBudget, ARRIVAL_ITEMS, TEMP_STAY, HOUSING, FOOD, TRANSPORT,
  LIFESTYLE_ITEMS, FLIGHT_COST, VISA_COST, type BudgetInputs,
} from "@/lib/tools/budget";
import { formatAED, formatINR, aedToInr } from "@/lib/currency";

export const runtime = "nodejs";
export const maxDuration = 60;

function row(label: string, aed: number, suffix = "") {
  return `<tr><td>${label}</td><td style="text-align:right;white-space:nowrap">${formatAED(aed)}${suffix} <span class="inr">≈ ${formatINR(aedToInr(aed))}</span></td></tr>`;
}

function buildHtml(inputs: BudgetInputs, title?: string): string {
  const r = calculateBudget(inputs);
  const housing = HOUSING.find((o) => o.key === inputs.housingKey);
  const food = FOOD.find((o) => o.key === inputs.foodKey);
  const transport = TRANSPORT.find((o) => o.key === inputs.transportKey);
  const temp = TEMP_STAY.find((o) => o.key === inputs.tempStayKey);

  const oneTimeRows = [
    row(`Flight (${inputs.flightType === "roundtrip" ? "round trip" : "one way"})`, FLIGHT_COST[inputs.flightType]),
    row(`${inputs.durationMonths}-month visit visa`, VISA_COST[inputs.durationMonths] ?? 600),
    ...ARRIVAL_ITEMS.filter((o) => inputs.arrival.includes(o.key)).map((o) => row(o.label, o.aed)),
    ...(temp && inputs.tempNights > 0 ? [row(`${temp.label} × ${inputs.tempNights} nights`, temp.aed * inputs.tempNights)] : []),
    ...(housing ? [row("Housing deposit (~40%)", Math.round(housing.aed * 0.4))] : []),
  ].join("");

  const monthlyRows = [
    ...(housing ? [row(`Rent, ${housing.label}`, housing.aed, "/mo")] : []),
    ...(food ? [row(`Food, ${food.label}`, food.aed, "/mo")] : []),
    ...(transport ? [row(`Transport, ${transport.label}`, transport.aed, "/mo")] : []),
    ...LIFESTYLE_ITEMS.filter((o) => inputs.lifestyle.includes(o.key)).map((o) => row(o.label, o.aed, "/mo")),
  ].join("");

  return `<!doctype html><html><head><meta charset="utf-8"/><style>
    @page { size: A4; margin: 16mm; }
    body { font: 13px/1.5 system-ui, sans-serif; color: #1f2328; }
    h1 { font-size: 20px; margin: 0; } .sub { color:#6b7077; font-size: 11px; margin: 2px 0 18px; }
    .total { background:#1A1D3E; color:#fff; border-radius:10px; padding:16px 20px; margin-bottom:18px; }
    .total b { font-size: 24px; }
    .grid { display:flex; gap:12px; margin-bottom: 18px; }
    .cell { flex:1; border:1px solid #e3e5ea; border-radius:8px; padding:10px 14px; }
    .cell span { display:block; font-size:10px; color:#6b7077; text-transform:uppercase; letter-spacing:.05em; }
    .cell b { font-size:15px; }
    h2 { font-size:12px; text-transform:uppercase; letter-spacing:.07em; color:#FF6B35; border-bottom:2px solid #FF6B35; padding-bottom:4px; margin:18px 0 8px; }
    table { width:100%; border-collapse:collapse; } td { padding:5px 0; border-bottom:1px solid #f0f1f4; }
    .inr { color:#9aa0ab; font-size:11px; }
    .foot { margin-top:24px; font-size:10px; color:#9aa0ab; }
  </style></head><body>
    <h1>${title?.trim() || "Dubai move-in budget"}</h1>
    <p class="sub">Dubaikar · ${inputs.durationMonths}-month plan · 1 AED = ₹25</p>
    <div class="total">Total cash needed<br/><b>${formatAED(r.totalAed)}</b> &nbsp; <span style="opacity:.8">≈ ${formatINR(aedToInr(r.totalAed))}</span></div>
    <div class="grid">
      <div class="cell"><span>One-time</span><b>${formatAED(r.oneTimeAed)}</b></div>
      <div class="cell"><span>Monthly</span><b>${formatAED(r.monthlyAed)}</b></div>
      <div class="cell"><span>Buffer (10%)</span><b>${formatAED(r.bufferAed)}</b></div>
    </div>
    <h2>One-time costs</h2><table>${oneTimeRows}</table>
    <h2>Monthly costs</h2><table>${monthlyRows}</table>
    <p class="foot">Generated by Dubaikar, dubaikar.com · amounts are estimates for planning.</p>
  </body></html>`;
}

export async function POST(request: NextRequest) {
  const supabase = await createClient();
  const {
    data: { user },
  } = await supabase.auth.getUser();
  if (!user) return NextResponse.json({ error: "Unauthorized" }, { status: 401 });

  let body: { inputs: BudgetInputs; title?: string };
  try {
    body = await request.json();
  } catch {
    return NextResponse.json({ error: "Invalid body" }, { status: 400 });
  }

  let browser;
  try {
    browser = await launchBrowser();
    const page = await browser.newPage();
    await page.setContent(buildHtml(body.inputs, body.title), { waitUntil: "load" });
    const pdf = await page.pdf({ format: "A4", printBackground: true });
    await browser.close();
    return new NextResponse(Buffer.from(pdf), {
      headers: {
        "Content-Type": "application/pdf",
        "Content-Disposition": 'attachment; filename="dubai-budget.pdf"',
      },
    });
  } catch (err) {
    if (browser) await browser.close().catch(() => {});
    console.error("Budget PDF failed:", err);
    return NextResponse.json({ error: "PDF generation failed" }, { status: 500 });
  }
}
